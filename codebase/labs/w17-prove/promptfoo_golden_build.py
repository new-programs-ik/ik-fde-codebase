"""Emit promptfoo-golden.yaml — one promptfoo test per golden case.

Regenerate whenever the golden set version changes:
    python3 promptfoo_golden_build.py
Run the agreement check (npx downloads promptfoo on first use):
    npx promptfoo@latest eval -c promptfoo-golden.yaml --no-cache
Both runners execute the identical pipeline + grading, so the promptfoo pass
count must equal `meridian-agent eval --suite golden` exactly.
"""
import sys
from pathlib import Path

_REPO = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(_REPO / "platform" / "agent" / "src"))

from meridian_agent.golden import load_golden  # noqa: E402

HEADER = """\
# GENERATED by promptfoo_golden_build.py — do not hand-edit.
# The portable second runner for the W17 golden gate (150 cases).
# PASS/FAIL per case must agree with: meridian-agent eval --suite golden
description: "Meridian golden dispute suite v{version} — execution-graded via golden_provider.py"

prompts:
  - "{{{{case_id}}}}"

providers:
  - id: file://golden_provider.py
    label: meridian-reference-pipeline

defaultTest:
  assert:
    - type: equals
      value: PASS

tests:
"""


def main() -> None:
    g = load_golden()
    lines = [HEADER.format(version=g["version"])]
    for c in g["cases"]:
        title = c["title"].replace('"', "'")[:80]
        lines.append(f'  - description: "{c["case_id"]} ({c["category"]}) {title}"\n'
                     f"    vars:\n"
                     f'      case_id: "{c["case_id"]}"\n')
    out = Path(__file__).parent / "promptfoo-golden.yaml"
    out.write_text("".join(lines))
    print(f"WROTE {out} ({len(g['cases'])} tests)")


if __name__ == "__main__":
    main()

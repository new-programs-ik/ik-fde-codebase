"""Promptfoo provider for the Meridian golden suite (DoD A4.1 agreement runner).

Promptfoo and `meridian-agent eval --suite golden` must AGREE on pass/fail per
case — this provider runs the same execution-graded pipeline per case_id and
returns PASS, or FAIL with the field mismatches, so a promptfoo `equals: PASS`
assert reproduces the gate verdict case-by-case.

Used by promptfoo-golden.yaml (generated by promptfoo_golden_build.py).
"""
import json
import os
import sys
from pathlib import Path

# resolve the agent package in either layout:
#   legacy layout:    <repo>/platform/agent/src   (this file 3 levels deep)
#   learner repo:     <repo>/agent/src            (this file 2 levels deep)
_HERE = Path(__file__).resolve()
for _cand in (_HERE.parents[3] / "platform" / "agent" / "src",
              _HERE.parents[2] / "agent" / "src",
              Path(os.environ.get("MERIDIAN_AGENT_SRC", "/nonexistent"))):
    if (_cand / "meridian_agent").is_dir():
        sys.path.insert(0, str(_cand))
        break

from meridian_agent.golden import grade_case, load_golden, run_case_quiet  # noqa: E402

_GOLDEN = load_golden()
_CASES = {c["case_id"]: c for c in _GOLDEN["cases"]}


def call_api(prompt, options=None, context=None):
    case_id = prompt.strip()
    case = _CASES.get(case_id)
    if case is None:
        return {"output": f"FAIL: unknown case_id {case_id!r}"}
    actual = run_case_quiet(case, _GOLDEN["base_policy_chunks"])
    graded = grade_case(case, actual)
    if graded["pass"]:
        return {"output": "PASS"}
    detail = {"mismatches": graded["mismatches"], "leaks": graded["leaks"]}
    return {"output": "FAIL: " + json.dumps(detail, default=str)}


if __name__ == "__main__":
    # quick self-test: run every case, print the promptfoo-visible verdicts
    fails = 0
    for cid in _CASES:
        out = call_api(cid)["output"]
        if out != "PASS":
            fails += 1
            print(cid, out[:160])
    print(f"self-test: {len(_CASES) - fails}/{len(_CASES)} PASS")
    raise SystemExit(1 if fails else 0)
